export type MessageKey = keyof typeof COPY.en;

export function t(key: MessageKey, variables: Variables = {}, locale = getActiveLocale()): string {
  const table = COPY[locale] as Record<MessageKey, string>;
  let result: string = table[key] ?? COPY.en[key];
  for (const [name, value] of Object.entries(variables)) result = result.replaceAll(`{${name}}`, String(value));
  return result;
}
